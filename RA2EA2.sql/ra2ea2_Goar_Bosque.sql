Create role empleats superuser createdb createrole inherit login replication;
ALTER user empleats with password 'empleats';
CREATE database empleats with owner empleats;
GRANT ALL PRIVILEGES ON DATABASE empleats TO empleats;

CREATE TABLE IF NOT EXISTS REGION (
CODI NUMERIC(6) NOT NULL,
NOMBRE VARCHAR(45),

CONSTRAINT PK_REGION PRIMARY KEY (CODI));

CREATE TABLE IF NOT EXISTS PROVINCIA (
CODI NUMERIC(6) NOT NULL,
NOMBRE VARCHAR(45),
COD:REGION NUMERIC(6)

CONSTRAINT PK_PROVINCIA PRIMARY KEY (CODI),
CONSTRAINT fk_prov_reg FOREIGN KEY (COD_REGION) REFERENCES REGION (COD_REGION)
);

CREATE TABLE IF NOT EXISTS LOCALIDAD (
CODI NUMERIC(6) NOT NULL,
NOMBRE VARCHAR(45),
COD:PROVINCIA NUMERIC(6)

CONSTRAINT PK_LOCALIDAD PRIMARY KEY (CODI),
CONSTRAINT fk_loc_prov FOREIGN KEY (COD_LOCALIDAD) REFERENCES LOCALIDAD (COD_LOCALIDAD)
);

CREATE TABLE IF NOT EXISTS EMPLEAT (
ID NUMERIC(6),
DNI VARCHAR(9),
NOMBRE VARCHAR(15),
FECHA_NAC DATE,
TELEFON NUMERIC (18),
SALARIO NUMERIC (18,5),
COD:LOCALIDAD NUMERIC(10),

CONSTRAINT pk_empleat PRIMARY KEY (ID),
CONSTRAINT fk_emp_loc FOREIGN KEY (COD_LOCALIDAD) REFERENCES LOCALIDAD (COD_LOCALIDAD),
CONSTRAINT uq_dni UNIQUE (DNI)
);